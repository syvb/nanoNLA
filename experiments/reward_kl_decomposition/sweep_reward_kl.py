"""Per-token-position decomposition of the nanoNLA Qwen3-8B RL training signal:
reconstruction reward vs KL penalty.

In the length-penalty sweep run that produced `syvb/nanonla-qwen3-8b-L24-rl-lora`
(vast_ops/05_rl_sweep.sh + nla/train_rl_self_contained.py), the two signals
enter the GRPO loss differently:

  - RECONSTRUCTION is sequence-level: reward = -mse_nrm(critic(explanation),
    gold) on the FULL <explanation>...</explanation> payload (no truncation),
    broadcast over the response tokens as a group-normalized advantage. Its
    per-position structure is therefore counterfactual: the marginal reward
    dr(t) = r(t) - r(t-1) of the first-t-token prefix, measured with the same
    frozen critic + critic_predict path used for the training reward.
  - KL is per-token: kl_beta * k3_t with k3 = exp(d) - d - 1,
    d = log pi_ref(x_t) - log pi(x_t) at the sampled token; ref = the AV-SFT
    policy (LoRA disabled), kl_beta = 0.01 in the sweep.

This script analyses the VANILLA arm (p0.0 — zero length penalty):
policy = merged AV-SFT + p0.0 LoRA, ref = the same model with the adapter
disabled (exactly the training anchor), critic = the frozen AR.

For N held-out rows (rl_shuf rows >= SKIP, the sweep's eval convention, with
activation_vector regenerated by tools/regenerate_activations.py):
  1. batched rollouts at T=1 (top_p=1, top_k=0), max_new=160 — the training
     rollout distribution;
  2. teacher-force each sequence with the adapter ON and OFF -> per-position
     k3 (the trained estimator), k1, and exact full-vocab KL;
  3. critic-score every response-token prefix, extracting the explanation
     open-tolerantly (payload after <explanation>, up to </explanation> if
     present; contentless -> the -2.0 failed-extraction floor) so the reward
     axis aligns 1:1 with the KL axis.

Outputs in $OUTDIR: per_sample.npz, aggregate.csv, responses.json.
"""
import json
import os
import sys
import unicodedata

import numpy as np
import pyarrow.parquet as pq
import torch
import torch.nn.functional as F
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer

from nla.config import load_nla_config
from nla.injection import karvonen_inject_in_residual
from nla.models import NLACriticModel
from nla.schema import (
    EXPLANATION_CLOSE,
    EXPLANATION_OPEN,
    normalize_activation,
    resolve_target_scale,
)
from nla.train_rl_self_contained import critic_predict

AV_DIR = os.environ.get("AV_DIR", "/workspace/av")
LORA_DIR = os.environ.get("LORA_DIR", "/workspace/rl_lora/p0.0")
AR_DIR = os.environ.get("AR_DIR", "/workspace/ar")
EVAL = os.environ.get("EVAL", "/workspace/data/rl_eval_full.parquet")
SIDECAR = os.environ.get("SIDECAR", EVAL)
OUTDIR = os.environ.get("OUTDIR", "/workspace/out/rkl")
os.makedirs(OUTDIR, exist_ok=True)
N = int(sys.argv[1]) if len(sys.argv) > 1 else 200
MAX_NEW = int(os.environ.get("MAX_NEW", "160"))  # RL_MAX_NEW in the sweep
TEMP = float(os.environ.get("NLA_GEN_TEMP", "1.0"))
SEED = int(os.environ.get("NLA_GEN_SEED", "0"))
FAILED_REWARD = -2.0
dev = "cuda"

tok = AutoTokenizer.from_pretrained(AV_DIR)
cfg = load_nla_config(SIDECAR, tok)
inj_id = cfg.injection_token_id
left_id = cfg.injection_left_neighbor_id
right_id = cfg.injection_right_neighbor_id
inject_char = cfg.injection_char
mse_scale_f = resolve_target_scale(cfg.mse_scale, cfg.d_model)
template = cfg.critic_prompt_template
assert template is not None


def extract_explanation_open(response: str) -> str | None:
    """Open-tolerant variant of nla.schema.extract_explanation for PREFIX
    scoring: a truncated response has the opening tag but no closing tag yet.
    Payload after <explanation>, up to </explanation> if present, stripped;
    empty/absent-opening -> None (the failed-extraction floor), matching how
    a rollout that never opened the tag is rewarded in training."""
    i = response.find(EXPLANATION_OPEN)
    if i == -1:
        return None
    payload = response[i + len(EXPLANATION_OPEN):]
    j = payload.find(EXPLANATION_CLOSE)
    if j != -1:
        payload = payload[:j]
    return payload.strip() or None


def cjk_frac(text):
    if not text:
        return 0.0
    return sum(1 for c in text if "CJK" in unicodedata.name(c, "")) / len(text)


def register_karvonen_hook(model, vectors_ref, layer_idx=1):
    """Same hook as scripts/eval_post_rl.py / the RL trainer: stash input_ids
    via an embedding hook, ADD the norm-matched vector at marker positions on
    layer `layer_idx`'s output. Reads vectors_ref[0] ([N, d] raw vectors, one
    per marker in the current batch, row-major)."""
    state = {"input_ids": None}

    def embed_hook(module, args, kwargs, output):
        ids = kwargs.get("input") if kwargs else None
        if ids is None and args:
            ids = args[0]
        state["input_ids"] = ids
        return output

    def layer_hook(module, args, output):
        resid, rest = (output[0], output[1:]) if isinstance(output, tuple) else (output, None)
        input_ids = state["input_ids"]
        if input_ids is None or resid.shape[1] < 2:
            return output
        v = vectors_ref[0]
        if v is None or v.shape[0] == 0:
            return output
        if (input_ids == inj_id).sum().item() == 0:
            return output
        injected = karvonen_inject_in_residual(input_ids, resid, v, inj_id, left_id, right_id)
        return injected if rest is None else (injected, *rest)

    model.get_input_embeddings().register_forward_hook(embed_hook, with_kwargs=True)
    target = model.base_model if hasattr(model, "base_model") else model
    while hasattr(target, "model") and not hasattr(target, "layers"):
        target = target.model
    target.layers[layer_idx].register_forward_hook(layer_hook)


# ---- held-out rows (activation_vector regenerated by setup_box.sh) ----
t_ = pq.read_table(EVAL, columns=["prompt", "activation_vector"])
assert t_.num_rows >= N, f"eval parquet has {t_.num_rows} rows < N={N}"
prompts = t_.column("prompt").to_pylist()[:N]
vecs = [np.asarray(v, dtype=np.float32) for v in t_.column("activation_vector").to_pylist()[:N]]
print(f"loaded {N} held-out rows from {EVAL}", flush=True)

prompt_ids = []
for p in prompts:
    msgs = [{**m, "content": m["content"].replace("<INJECT>", inject_char)}
            if isinstance(m.get("content"), str) else m for m in p]
    text = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
    prompt_ids.append(tok.encode(text, add_special_tokens=False))
V = torch.stack([torch.tensor(v) for v in vecs])  # raw — the Karvonen hook norm-matches

# ---- policy = merged AV-SFT + p0.0 RL LoRA; ref = same model, adapter off ----
actor = AutoModelForCausalLM.from_pretrained(
    AV_DIR, dtype=torch.bfloat16, attn_implementation="sdpa",
).to(dev)
actor = PeftModel.from_pretrained(actor, LORA_DIR)
actor.eval()
vectors_ref = [None]
register_karvonen_hook(actor, vectors_ref)

_eos_cfg = actor.generation_config.eos_token_id
EOS_IDS = set(_eos_cfg if isinstance(_eos_cfg, list) else [_eos_cfg]) | {tok.eos_token_id}
pad_id = tok.pad_token_id if tok.pad_token_id is not None else tok.eos_token_id

# ---- phase 1: batched rollouts at T=1 (left-pad, like rollout_batch) ----
torch.manual_seed(SEED)
resp_ids, has_eos, texts = [], [], []
ncjk = 0
BG = 32
for s in range(0, N, BG):
    idx = list(range(s, min(s + BG, N)))
    m = max(len(prompt_ids[i]) for i in idx)
    inp = np.full((len(idx), m), pad_id, dtype=np.int64)
    att = np.zeros((len(idx), m), dtype=np.int64)
    for k, i in enumerate(idx):
        inp[k, m - len(prompt_ids[i]):] = prompt_ids[i]
        att[k, m - len(prompt_ids[i]):] = 1
    inp_t = torch.tensor(inp, device=dev)
    att_t = torch.tensor(att, device=dev)
    vectors_ref[0] = V[idx].to(dev)
    try:
        with torch.no_grad():
            out = actor.generate(
                input_ids=inp_t, attention_mask=att_t, max_new_tokens=MAX_NEW,
                do_sample=True, temperature=TEMP, top_p=1.0, top_k=0,
                pad_token_id=pad_id,
            )
    finally:
        vectors_ref[0] = None
    for row in out[:, m:].tolist():
        eos_at = next((k for k, x in enumerate(row) if x in EOS_IDS), None)
        if eos_at is not None:
            row = row[: eos_at + 1]
            has_eos.append(True)
        else:
            has_eos.append(False)
        resp_ids.append(row)
        txt = tok.decode(row, skip_special_tokens=True)
        texts.append(txt)
        if cjk_frac(txt) > 0:
            ncjk += 1
    print(f"  gen {len(resp_ids)}/{N} (cjk={ncjk})", flush=True)
resp_len = [len(r) for r in resp_ids]
print(f"gen done: resp len median={int(np.median(resp_len))} max={max(resp_len)} "
      f"eos={sum(has_eos)}/{N} cjk={ncjk}", flush=True)

# ---- phase 2: per-position KL, adapter ON vs OFF (the training anchor) ----
Rmax = max(resp_len)
k1_mat = np.full((N, Rmax), np.nan, dtype=np.float32)
k3_mat = np.full((N, Rmax), np.nan, dtype=np.float32)
klx_mat = np.full((N, Rmax), np.nan, dtype=np.float32)


@torch.no_grad()
def resp_logprobs(ids, i, P, R):
    vectors_ref[0] = V[i : i + 1].to(dev)
    try:
        logits = actor(input_ids=ids).logits[0, P - 1 : P - 1 + R]
    finally:
        vectors_ref[0] = None
    return torch.log_softmax(logits.float(), dim=-1)


for i in range(N):
    ids = torch.tensor([prompt_ids[i] + resp_ids[i]], device=dev)
    P, R = len(prompt_ids[i]), resp_len[i]
    lp_pol = resp_logprobs(ids, i, P, R)
    with actor.disable_adapter():
        lp_ref = resp_logprobs(ids, i, P, R)
    xt = torch.tensor(resp_ids[i], device=dev)
    pol = lp_pol.gather(1, xt[:, None])[:, 0]
    ref = lp_ref.gather(1, xt[:, None])[:, 0]
    delta = ref - pol
    k1_mat[i, :R] = (-delta).cpu().numpy()
    k3_mat[i, :R] = (torch.exp(delta) - delta - 1.0).cpu().numpy()
    klx_mat[i, :R] = (lp_pol.exp() * (lp_pol - lp_ref)).sum(-1).cpu().numpy()
    if (i + 1) % 25 == 0:
        print(f"  KL {i + 1}/{N}", flush=True)
print(f"KL done: mean k3={np.nanmean(k3_mat):.4f} k1={np.nanmean(k1_mat):.4f} "
      f"exact={np.nanmean(klx_mat):.4f}", flush=True)

del actor
torch.cuda.empty_cache()

# ---- phase 3: critic reward per response-token prefix ----
critic = NLACriticModel.from_pretrained(AR_DIR, torch_dtype=torch.bfloat16).to(dev)
critic.eval()
assert torch.isfinite(critic.value_head.weight).all(), "non-finite value head"
gn = normalize_activation(torch.stack([torch.tensor(v) for v in vecs]).float(), mse_scale_f)

jobs = []  # (i, t, explanation | None); t = response-token prefix length
for i in range(N):
    for tt in range(0, resp_len[i] + 1):
        jobs.append((i, tt, extract_explanation_open(tok.decode(resp_ids[i][:tt], skip_special_tokens=True))))
reward_mat = np.full((N, Rmax + 1), np.nan, dtype=np.float32)
for i, tt, e in jobs:
    if e is None:
        reward_mat[i, tt] = FAILED_REWARD
live = [(i, tt, e) for i, tt, e in jobs if e is not None]
print(f"critic jobs: {len(live)} scoreable / {len(jobs)}", flush=True)
BS = 64
for b in range(0, len(live), BS):
    chunk = live[b : b + BS]
    enc = [tok.encode(template.format(explanation=e), add_special_tokens=False) for _, _, e in chunk]
    m = max(len(x) for x in enc)
    ids = np.full((len(enc), m), pad_id, dtype=np.int64)
    am = np.zeros((len(enc), m), dtype=np.int64)
    for k, x in enumerate(enc):  # right-pad; critic_predict reads attn.sum-1
        ids[k, : len(x)] = x
        am[k, : len(x)] = 1
    with torch.no_grad():
        pred = critic_predict(critic, torch.tensor(ids, device=dev),
                              torch.tensor(am, device=dev), mse_scale_f).cpu()
    pn = normalize_activation(pred, mse_scale_f)
    for (i, tt, _), p in zip(chunk, pn):
        mse = F.mse_loss(p, gn[i]).item()
        reward_mat[i, tt] = -mse if np.isfinite(mse) else FAILED_REWARD
    if (b // BS) % 20 == 0:
        print(f"  critic {b}/{len(live)}", flush=True)
full_r = [reward_mat[i, resp_len[i]] for i in range(N)]
print(f"critic done: mean full-length reward={np.mean(full_r):.4f}", flush=True)

# first content position per sample (where the open-tolerant extraction starts
# succeeding) — before it the reward sits at the -2.0 floor
content_start = np.full(N, -1, dtype=np.int64)
for i in range(N):
    for tt in range(0, resp_len[i] + 1):
        if reward_mat[i, tt] != FAILED_REWARD:
            content_start[i] = tt
            break

np.savez_compressed(
    f"{OUTDIR}/per_sample.npz", reward=reward_mat, k1=k1_mat, k3=k3_mat,
    kl_exact=klx_mat, resp_len=np.array(resp_len), has_eos=np.array(has_eos),
    content_start=content_start, gen_temp=TEMP, seed=SEED,
)
json.dump([{"i": i, "text": texts[i], "resp_len": resp_len[i],
            "content_start": int(content_start[i]), "has_eos": bool(has_eos[i])}
           for i in range(N)], open(f"{OUTDIR}/responses.json", "w"), indent=1)

with open(f"{OUTDIR}/aggregate.csv", "w") as fh:
    fh.write("t,n_alive,mean_reward,mean_marginal,mean_k1,mean_k3,mean_kl_exact\n")
    for tt in range(1, Rmax + 1):
        alive = [i for i in range(N) if resp_len[i] >= tt]
        r = np.mean([reward_mat[i, tt] for i in alive])
        dr = np.mean([reward_mat[i, tt] - reward_mat[i, tt - 1] for i in alive])
        fh.write(f"{tt},{len(alive)},{r:.6f},{dr:.6f},{np.nanmean(k1_mat[:, tt-1]):.6f},"
                 f"{np.nanmean(k3_mat[:, tt-1]):.6f},{np.nanmean(klx_mat[:, tt-1]):.6f}\n")
print(f"content_start: median={int(np.median(content_start[content_start >= 0]))} "
      f"never={int((content_start < 0).sum())}", flush=True)
print("RKL_DONE", flush=True)
